-- =====================================================================
-- CENSO SUAS — REGISTRO DE ENVIO (quando e como o Censo saiu da TEIAA)
-- ---------------------------------------------------------------------
--  * censo_suas.envios: lista de envios [{ data, meio, ident, para, por,
--    obs, arquivo, arquivo_nome, oficio_id }]. Coluna própria: o link do
--    administrativo (censo_link_salvar_censo) não mexe nela.
--  * storage 'censo' (PRIVADO): comprovantes (ofício protocolado, print do
--    e-mail...). Só admin e operacional leem/gravam; abre por link
--    temporário (signed URL).
--  * oficios: ofícios da TEIAA com numeração automática por ano (o ofício
--    de encaminhamento do Censo nasce aqui; mesma estrutura da CAPETTE).
--
-- Como rodar: Supabase (projeto da TEIAA) -> SQL Editor -> New query ->
-- colar -> Run. Idempotente. Rodar ANTES do deploy.
-- =====================================================================

alter table public.censo_suas add column if not exists envios jsonb not null default '[]'::jsonb;

insert into storage.buckets (id, name, public) values ('censo', 'censo', false) on conflict (id) do nothing;

drop policy if exists "Censo: admin e operacional leem comprovantes" on storage.objects;
create policy "Censo: admin e operacional leem comprovantes" on storage.objects for select to authenticated
  using (bucket_id = 'censo' and public.perfil_atual() in ('admin','operacional'));
drop policy if exists "Censo: admin e operacional enviam comprovantes" on storage.objects;
create policy "Censo: admin e operacional enviam comprovantes" on storage.objects for insert to authenticated
  with check (bucket_id = 'censo' and public.perfil_atual() in ('admin','operacional'));
drop policy if exists "Censo: admin e operacional apagam comprovantes" on storage.objects;
create policy "Censo: admin e operacional apagam comprovantes" on storage.objects for delete to authenticated
  using (bucket_id = 'censo' and public.perfil_atual() in ('admin','operacional'));

-- Ofícios (numeração por ano)
create table if not exists public.oficios (
  id bigint generated by default as identity primary key,
  numero integer not null,
  ano integer not null default extract(year from current_date)::int,
  data date not null default current_date,
  destinatario text,
  cargo_destinatario text,
  orgao_destinatario text,
  assunto text not null,
  corpo text not null,
  com_assinatura boolean not null default false,
  criado_em timestamptz default now(),
  unique (numero, ano)
);
alter table public.oficios enable row level security;
drop policy if exists "Admin e operacional gerenciam oficios" on public.oficios;
create policy "Admin e operacional gerenciam oficios" on public.oficios for all to authenticated
  using (public.perfil_atual() in ('admin','operacional'))
  with check (public.perfil_atual() in ('admin','operacional'));
grant select, insert, update, delete on public.oficios to authenticated;

notify pgrst, 'reload schema';
